            const form = document.querySelector("#generator");
            const submit = form.querySelector('button[type="submit"]');
            const cancel = document.querySelector("#cancel");
            const progress = document.querySelector("#progress");
            const status = document.querySelector("#status");
            const generatedMetric = document.querySelector("#generated");
            const requestsMetric = document.querySelector("#requests");
            const history = document.querySelector("#history");
            let controller;

            const sleep = (milliseconds) => new Promise((resolve) => setTimeout(resolve, milliseconds));
            const value = (selector) => document.querySelector(selector).value;

            cancel.addEventListener("click", () => controller?.abort());

            form.addEventListener("submit", async (event) => {
              event.preventDefault();
              const total = Number(value("#count"));
              const batchSize = Number(value("#batch-size"));
              const delay = Number(value("#delay"));
              const scenario = value("#scenario");
              const enteredSeed = value("#seed");
              const baseSeed = enteredSeed ? Number(enteredSeed) : Math.floor(Math.random() * 2_147_483_647);
              let generated = 0;
              let requests = 0;
              controller = new AbortController();

              submit.disabled = true;
              cancel.disabled = false;
              status.classList.remove("error");
              history.replaceChildren();
              progress.style.width = "0%";
              generatedMetric.textContent = "0";
              requestsMetric.textContent = "0";

              try {
                while (generated < total) {
                  const count = Math.min(batchSize, total - generated);
                  const response = await fetch(location.pathname, {
                    method: "POST",
                    headers: { "Content-Type": "application/json", "Accept": "application/json" },
                    body: JSON.stringify({ scenario, count, seed: baseSeed + requests }),
                    signal: controller.signal,
                  });
                  const result = await response.json();
                  if (!response.ok) throw new Error(result.error || `Request failed (${response.status})`);

                  generated += result.generated;
                  requests += 1;
                  const percent = Math.round((generated / total) * 100);
                  progress.style.width = `${percent}%`;
                  generatedMetric.textContent = generated.toLocaleString();
                  requestsMetric.textContent = requests.toLocaleString();
                  status.textContent = `Generated ${generated.toLocaleString()} of ${total.toLocaleString()} (${percent}%)`;

                  const item = document.createElement("li");
                  item.textContent = `batch ${requests}: +${result.generated}, seed ${result.seed}, ${JSON.stringify(result.severities)}`;
                  history.prepend(item);
                  if (generated < total && delay > 0) await sleep(delay);
                }
                status.innerHTML = `Complete — <a href="/logs/">inspect ${generated.toLocaleString()} generated reports</a>.`;
              } catch (error) {
                status.classList.add("error");
                status.textContent = error.name === "AbortError" ? `Cancelled after ${generated.toLocaleString()} reports.` : error.message;
              } finally {
                submit.disabled = false;
                cancel.disabled = true;
                controller = undefined;
              }
            });
