class Sample < Sinatra::Base
  use Logster::Middleware::Viewer
  use Logster::Middleware::Reporter

  get "/" do
    <<~HTML
      <!doctype html>
      <html lang="en">
        <head><meta charset="utf-8"><title>Logster development</title></head>
        <body>
          <h3>Welcome to Logster</h3>
          <ul>
            <li><a href="https://github.com/discourse/logster">Learn about Logster</a></li>
            <li><a href="/logs/">View sample development logs</a></li>
            <li><a href="/report_error">Generate rich test data</a></li>
          </ul>
        </body>
      </html>
    HTML
  end

  # This route is deliberately read-only. Reports are only generated by POST.
  get "/report_error" do
    content_type :html
    report_error_page
  end

  post "/report_error" do
    content_type :json
    payload = report_payload
    result =
      SampleLoaderInstance.report_scenario(
        scenario: payload.fetch("scenario", "mixed"),
        count: payload.fetch("count", 1),
        seed: payload["seed"],
      )
    status 201
    JSON.generate(result.merge(viewer_url: "/logs/"))
  rescue JSON::ParserError => error
    halt 400, JSON.generate(error: "Invalid JSON: #{error.message}")
  rescue KeyError, ArgumentError => error
    halt 422, JSON.generate(error: error.message)
  end

  private

  def report_payload
    return params if request.media_type != "application/json"

    body = request.body.read
    body.empty? ? {} : JSON.parse(body)
  end

  def scenario_options
    SampleLoader::SCENARIOS
      .map do |value, description|
        %(<option value="#{value}">#{value.capitalize} — #{description}</option>)
      end
      .join("\n")
  end

